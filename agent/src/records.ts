export interface ReaderSummary {
  reader: 'A' | 'B';
  model: string;
  ok: boolean;
  verified: boolean;
  signature_kind: string | null;
  /** Signed inside the model's own TEE (provider_tee). Absent in older records. */
  tee?: boolean;
  e2ee: boolean;
  /** Why the request fell back to plaintext, if it did. */
  e2ee_fallback_reason?: string | null;
  error: string | null;
}

/** NormalizedInvoice with bigints as strings (JSON). */
export interface InvoiceFields {
  vendor_name: string;
  vendor_account: string | null;
  invoice_number: string;
  issue_date: string | null;
  due_date: string | null;
  currency: string;
  amount_base_units: string | null;
  line_items: { description: string; amount_base_units: string | null }[];
  payment_instructions_text: string | null;
}

export type RecordMode = 'execute' | 'dry-run' | 'analyze';

export interface InvoiceRecord {
  version: 1;
  id: string;
  received_at: string;
  original_name: string;
  /** Stored original, relative to the files dir. */
  file: string;
  /** First page as PNG/JPEG, relative to the files dir (null if it could not be rendered). */
  page_image: string | null;
  page_size: { width: number; height: number } | null;
  pages: number;
  network: string;
  treasury: string;
  registry: string;
  mode: RecordMode;
  /** PayOutcome, or 'analyzed' (analyze-only) / 'error' (the run crashed). */
  outcome: string;
  message: string;
  invoice_hash: string | null;
  decision: Decision | null;
  invoice: InvoiceFields | null;
  boxes: Boxes | null;
  readers: ReaderSummary[];
  agree: boolean | null;
  disagreements: string[];
  chain_error: string | null;
  registry_entry: VendorView | null;
  vendor_policy: VendorPolicy | null;
  config: TreasuryConfig | null;
  vendor_paid_count: number;
  path: string | null;
  quote: {
    amount_out_formatted?: string; time_estimate_s?: number; quote_hash: string | null; simulated: boolean;
    /** Evidence for the owner (absent in records written before the review fixes). */
    signature_valid?: boolean; recipient_matches_registry?: boolean; checks_ok?: boolean;
    recipient?: string; deposit_address?: string | null; deadline?: string;
  } | null;
  deposit_address: string | null;
  agent_flags: string[];
  tx_hash: string | null;
  explorer_url: string | null;
  payment_id: number | null;
  payment: Payment | null;
}

export const defaultFilesDir = (env: NodeJS.ProcessEnv = process.env) =>
  env.ORVANTRA_FILES_DIR ?? resolve(dirname(defaultLedgerPath(env)), 'files');

/** Upload ids are generated by the web server; only this shape is ever accepted as a path component. */
export const RECORD_ID = /^[0-9]{13}-[0-9a-f]{8}$/;

export function newRecordId(now = Date.now(), rand = () => Math.floor(Math.random() * 0x100000000)): string {
  return `${String(now).padStart(13, '0')}-${rand().toString(16).padStart(8, '0').slice(0, 8)}`;
}

export function writeRecord(dir: string, rec: InvoiceRecord): void {
  if (!RECORD_ID.test(rec.id)) throw new Error(`bad record id ${rec.id}`);
  mkdirSync(dir, { recursive: true });
  const path = join(dir, `${rec.id}.json`);
  const tmp = `${path}.${process.pid}.tmp`;
  writeFileSync(tmp, `${JSON.stringify(rec, (_k, v) => (typeof v === 'bigint' ? v.toString() : v), 2)}\n`);
  renameSync(tmp, path);
}

export function readRecord(dir: string, id: string): InvoiceRecord | null {
  if (!RECORD_ID.test(id)) return null;
  const path = join(dir, `${id}.json`);
  if (!existsSync(path)) return null;
  try {
    return JSON.parse(readFileSync(path, 'utf8')) as InvoiceRecord;
  } catch {
    return null;
  }
}

/** All records, newest first. Unreadable files are skipped. */
export function listRecords(dir: string): InvoiceRecord[] {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith('.json') && RECORD_ID.test(f.slice(0, -5)))
    .map((f) => readRecord(dir, f.slice(0, -5)))
    .filter((r): r is InvoiceRecord => r !== null)
    .sort((a, b) => b.received_at.localeCompare(a.received_at));
}

/** Pixel size of a PNG or JPEG (null for anything else or a truncated file). */
export function imageSize(buf: Buffer): { width: number; height: number } | null {
  if (buf.length >= 24 && buf.readUInt32BE(0) === 0x89504e47 && buf.subarray(12, 16).toString('latin1') === 'IHDR') {
    return { width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) };
  }
  if (buf.length >= 4 && buf[0] === 0xff && buf[1] === 0xd8) {
    let i = 2;
    while (i + 9 < buf.length) {
      if (buf[i] !== 0xff) return null;
      const marker = buf[i + 1];
      const len = buf.readUInt16BE(i + 2);
      // SOF0..SOF15 except DHT (C4), JPG (C8), DAC (CC)
      if (marker >= 0xc0 && marker <= 0xcf && marker !== 0xc4 && marker !== 0xc8 && marker !== 0xcc) {
        return { width: buf.readUInt16BE(i + 7), height: buf.readUInt16BE(i + 5) };
      }
      i += 2 + len;
    }
  }
  return null;
}
