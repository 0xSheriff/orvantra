// One JSON record per invoice the web app received (agent/data/files/<id>.json, gitignored), next to the original
// file (<id>.<ext>) and the first page as an image (<id>.page1.png|jpg). Written by src/web-run.ts, read by web/.
// The chain stays the source of truth for payment status; this is what the agent saw and decided.
